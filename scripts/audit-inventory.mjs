import { readFileSync, readdirSync, statSync, writeFileSync, mkdirSync } from 'node:fs';
import { join } from 'node:path';

const root = new URL('..', import.meta.url).pathname;
const skip = new Set(['src', 'scripts', 'node_modules', '.git', 'assets', 'docs']);
const files = [];
const walk = (dir) => {
  for (const name of readdirSync(dir)) {
    if (skip.has(name)) continue;
    const path = join(dir, name);
    if (statSync(path).isDirectory()) walk(path);
    else if (name.endsWith('.html')) files.push(path);
  }
};
walk(root);

const text = (value) => value.replace(/<script[\s\S]*?<\/script>|<style[\s\S]*?<\/style>|<[^>]+>/g, ' ').replace(/&[a-z#0-9]+;/g, ' ').replace(/\s+/g, ' ').trim();
const pick = (html, regex) => (html.match(regex) || [])[1] || '';

const rows = files.sort().map((file) => {
  const html = readFileSync(file, 'utf8');
  const url = '/' + file.replace(root, '').replace(/index\.html$/, '');
  const stub = /http-equiv="refresh"/.test(html);
  const types = [...html.matchAll(/"@type":"([A-Za-z]+)"/g)].map((m) => m[1]);
  const body = html.match(/<body[\s\S]*<\/body>/);
  return {
    url,
    lang: pick(html, /<html lang="([^"]+)"/),
    kind: stub ? 'redirect stub' : 'page',
    title: text(pick(html, /<title>([\s\S]*?)<\/title>/)),
    description: pick(html, /<meta name="description" content="([^"]*)"/),
    h1: text(pick(html, /<h1[^>]*>([\s\S]*?)<\/h1>/)),
    canonical: pick(html, /<link rel="canonical" href="([^"]*)"/),
    hreflang: (html.match(/rel="alternate" hreflang=/g) || []).length,
    robots: pick(html, /<meta name="robots" content="([^"]*)"/) || 'index',
    schema: [...new Set(types)].join(' '),
    words: body && !stub ? text(body[0]).split(' ').length : 0,
  };
});

const cell = (value) => String(value).replace(/\|/g, '/');
const head = '| URL | Lang | Type | Title | Meta description | H1 | Canonical | Hreflang | Robots | JSON-LD | Words |\n|---|---|---|---|---|---|---|---|---|---|---|\n';
const body = rows.map((r) => `| ${[r.url, r.lang, r.kind, r.title, r.description.length + ' chars', r.h1, r.canonical.replace('https://www.kortexlab.me', ''), r.hreflang, r.robots, r.schema, r.words].map(cell).join(' | ')} |`).join('\n');
mkdirSync(join(root, 'docs/audit'), { recursive: true });
writeFileSync(join(root, 'docs/audit/00-inventory.md'), `# Inventory\n\n${rows.length} built HTML files, generated by scripts/audit-inventory.mjs.\n\n${head}${body}\n`);
console.log(`${rows.length} rows`);
